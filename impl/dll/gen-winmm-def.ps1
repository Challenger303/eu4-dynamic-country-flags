# gen-winmm-def.ps1 - generate the shim's forwarder tables from the real winmm.
#
# The shim must export everything the genuine winmm.dll exports, or some other
# component in the process (Steam overlay, EOS SDK, an audio driver) can fail to
# resolve an import that used to work. Rather than hand-maintaining that list,
# we read it out of System32 at build time.
#
# Every export becomes a PE *forwarder* to winmm_orig.dll - a verbatim copy of
# the genuine System32 winmm.dll that install.ps1 puts next to the shim. The
# Windows loader resolves forwarders itself, so a waveOutWrite call reaches the
# real waveOutWrite without executing one instruction of ours. That is why
# proxying winmm cannot break sound: there is no wrapper to get wrong.
#
# Two outputs, because of how MSVC's linker works:
#   winmm_orig.def      -> `lib /DEF:` turns this into a stub import library.
#                          link.exe refuses a forwarder whose target module it
#                          cannot see, so the stub exists purely to satisfy it.
#                          (Verified: this produces no actual import on
#                          winmm_orig.dll in the finished shim.)
#   winmm_exports.rsp   -> the /EXPORT: switches, as a response file. MSVC does
#                          NOT honour `name=other.func` forwarders written in a
#                          .def; it only honours them as /EXPORT: options.

param(
    [string]$Source = "$env:SystemRoot\System32\winmm.dll",
    [string]$OutDir = "$PSScriptRoot\shim",
    [string]$Target = "winmm_orig"
)

$ErrorActionPreference = "Stop"

$b = [IO.File]::ReadAllBytes($Source)
function U16($o) { [BitConverter]::ToUInt16($b, $o) }
function U32($o) { [BitConverter]::ToUInt32($b, $o) }

$pe = U32 0x3C
if ((U32 $pe) -ne 0x00004550) { throw "$Source is not a PE file" }
$coff = $pe + 4
$nsec = U16 ($coff + 2)
$osz  = U16 ($coff + 16)
$opt  = $coff + 20
if ((U16 $opt) -ne 0x20B) { throw "$Source is not 64-bit; the shim must match the game (x64)" }
$dd = $opt + 112

$secOff = $opt + $osz
$secs = @()
for ($i = 0; $i -lt $nsec; $i++) {
    $s = $secOff + $i * 40
    $secs += [pscustomobject]@{ vs = (U32 ($s+8)); va = (U32 ($s+12)); rs = (U32 ($s+16)); ra = (U32 ($s+20)) }
}
function R2O($r) {
    foreach ($s in $secs) {
        if ($r -ge $s.va -and $r -lt ($s.va + [Math]::Max($s.vs, $s.rs))) { return $s.ra + ($r - $s.va) }
    }
    return -1
}
function Str($r) {
    $o = R2O $r; if ($o -lt 0) { return $null }
    $e = $o; while ($b[$e] -ne 0) { $e++ }
    [Text.Encoding]::ASCII.GetString($b, $o, $e - $o)
}

$eo      = R2O (U32 $dd)
$ordBase = U32 ($eo + 16)
$nFunc   = U32 ($eo + 20)
$nName   = U32 ($eo + 24)
$fo = R2O (U32 ($eo + 28))
$no = R2O (U32 ($eo + 32))
$oo = R2O (U32 ($eo + 36))

$named = @{}
for ($i = 0; $i -lt $nName; $i++) { $named[[int](U16 ($oo + $i * 2))] = (Str (U32 ($no + $i * 4))) }

$defLines = @()
$rspLines = @()
$nNamed = 0
$nSkipped = 0

for ($i = 0; $i -lt $nFunc; $i++) {
    if ((U32 ($fo + $i * 4)) -eq 0) { continue }        # gap in the ordinal space
    $ord = $ordBase + $i
    if ($named.ContainsKey($i)) {
        $n = $named[$i]
        $defLines += ("    {0} @{1}" -f $n, $ord)
        $rspLines += ("/EXPORT:{0}={1}.{0},@{2}" -f $n, $Target, $ord)
        $nNamed++
    } else {
        # A nameless ordinal export. Nothing can import it by name, and a
        # by-ordinal import of winmm is not a thing any modern component does,
        # so it is dropped rather than guessed at. Reported, never silent.
        Write-Warning ("ordinal @{0} is a nameless export; not forwarded" -f $ord)
        $nSkipped++
    }
}

if (-not (Test-Path $OutDir)) { New-Item -ItemType Directory -Path $OutDir | Out-Null }

Set-Content -Path "$OutDir\winmm_orig.def" -Encoding ascii -Value (@(
    "; Generated by gen-winmm-def.ps1 - do not edit by hand.",
    "; A stub import library is built from this so the linker will accept",
    "; forwarders aimed at $Target.dll. It ships nothing and imports nothing.",
    "LIBRARY $Target",
    "EXPORTS") + $defLines)

# No comment header here: link.exe response files carry options only, and a
# comment line would be parsed as a bad option.
Set-Content -Path "$OutDir\winmm_exports.rsp" -Encoding ascii -Value $rspLines

Write-Output ("wrote winmm_orig.def + winmm_exports.rsp: {0} forwarders, {1} skipped" -f $nNamed, $nSkipped)
